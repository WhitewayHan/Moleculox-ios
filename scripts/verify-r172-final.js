const fs=require('fs');
const must=(x,m)=>{if(!x)throw new Error(m);};
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const manifest=JSON.parse(fs.readFileSync('www/manifest.webmanifest','utf8'));
const game=fs.readFileSync('www/js/game.js','utf8');
const idx=fs.readFileSync('www/index.html','utf8');
const css=fs.readFileSync('www/css/app.css','utf8');
const fb=fs.readFileSync('www/js/firebase.js','utf8');
must(pkg.version==='8.7.68'&&manifest.version==='8.7.68','R172 version mismatch');
must(game.includes('const APP_VERSION="v8.7.68";')&&idx.includes('8.7.68-r172-501-menu-ios'),'R172 build identity mismatch');
must(idx.includes('id="campaign501Badge"'),'501 campaign badge missing');
must(css.includes('R172 — QUIET 501-CAMPAIGN DISCOVERY')&&css.includes('#campaign501Badge'),'501 badge style missing');
must(game.includes('seen501CampaignIntro:false')&&game.includes('501 experiments')&&game.includes('501 DENEY'),'one-time 501 Dr. E intro missing');
must(game.includes("save.seen501CampaignIntro=true;persist();"),'501 intro persistence missing');
must(game.includes('all 501 experiments are complete'),'stale completed-campaign copy not updated');
must(!pkg.dependencies['@capacitor/local-notifications'],'Local Notifications dependency must be absent');
must(!/LocalNotifications|PushNotifications|Notification\.requestPermission|MX_RETURN_REMINDER_IDS|requestPermissions\s*\(.*notification/i.test(game),'OS notification runtime must be absent');
must(!/savePushToken|updatePushLang|pushTokens\/\{uid\}/i.test(fb),'push-token persistence must be absent');
must(game.includes('const BARRIER_USE_PRICE=300;'),'paid barrier regression');
must(game.includes('R171: GOAL is intentionally static'),'R171 static GOAL regression');
console.log('R172 ios 501-menu/no-notification checks passed.');
